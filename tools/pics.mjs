// Build pics.js (card id -> picture file) from pictures.json, and download the Twemoji SVGs (CC BY 4.0) into ../img.
// Run from app/v2/tools:  node pics.mjs
import fs from 'fs';
const map = JSON.parse(fs.readFileSync('pictures.json', 'utf8')); delete map._note;
globalThis.window = globalThis; eval(fs.readFileSync('../content.js', 'utf8'));
const code = e => { const cps = [...e].map(c => c.codePointAt(0).toString(16)); return (cps.includes('200d') ? cps : cps.filter(c => c !== 'fe0f')).join('-'); };
const key = de => de.split(/,|\(|\//)[0].trim().replace(/^(der|die|das) /, '').split(' ')[0];
const out = {}; const need = new Set(); const used = new Set();
for (const s of window.STORIES) for (const t of ['w', 'c', 'x']) s[t].forEach((r, i) => {
  const k = key(r[0]); if (t !== 'c' && map[k]) { const f = code(map[k]); out[`${s.n}:${t}:${i}`] = f; need.add(f); used.add(k); }
});
fs.mkdirSync('../img', { recursive: true });
for (const f of need) {
  const p = `../img/${f}.svg`; if (fs.existsSync(p)) continue;
  const r = await fetch(`https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/svg/${f}.svg`);
  if (!r.ok) { console.log('MISSING', f); continue; }
  const svg = await r.text(); if (!svg.startsWith('<svg')) { console.log('NOT SVG', f); continue; }
  fs.writeFileSync(p, svg);
}
fs.writeFileSync('../pics.js', '/* Generated by tools/pics.mjs. Pictures: Twemoji by Twitter/X and contributors, CC BY 4.0. */\nwindow.PICS = ' + JSON.stringify(out) + ';\n');
console.log('cards with a picture', Object.keys(out).length, '· pictures', need.size, '· unused keys', Object.keys(map).filter(k => !used.has(k)).join(', '));
